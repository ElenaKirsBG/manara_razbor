const suitOrder = ["air", "fire", "earth", "water"] as const;

const minorCards: ManaraCard[] = suitOrder.flatMap((suit) => {
  const suitSeed = suitSeeds[suit];
  return rankSeeds.map((rankSeed) => ({
    id: `${suit}-${rankSeed.rank}`,
    name: `${rankSeed.title} ${suitSeed.label}`,
    arcana: "minor" as const,
    suit,
    rank: rankSeed.rank,
    keywords: [...suitSeed.keywords.slice(0, 2), ...rankSeed.keywords],
    meaning: `${rankSeed.theme} в сфере ${suitSeed.theme}. Читайте карту как конкретный способ переживать или проявлять эту динамику, а не как неизменное описание личности.`,
    shadow: `${rankSeed.risk}; в масти ${suitSeed.label.toLowerCase()} это может выражаться через ${suitSeed.risk}.`,
    imageUrl: null,
  }));
});

const majorCards: ManaraCard[] = majorSeeds.map((card, index) => ({
  ...card,
  arcana: "major",
  suit: "major",
  rank: index,
  imageUrl: null,
}));

export const manaraCards: ManaraCard[] = [...majorCards, ...minorCards].map((card) => {
  const note = manaraKnowledge[card.id];
  if (!note) throw new Error(`Нет локальной справки для карты ${card.id}`);
  return {
    ...card,
    name: note.name,
    keywords: note.keywords,
    meaning: note.meaning,
    shadow: note.shadow,
  };
});

