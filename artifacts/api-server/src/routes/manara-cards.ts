export function getManaraCardsWithImages(): ManaraCard[] {
  return manaraCards.map((card) => ({
    ...card,
    imageUrl: `/cards/${card.id}.jpg`,
  }));
}

export function findManaraCards(cardIds: string[]): ManaraCard[] {
  const byId = new Map(manaraCards.map((card) => [card.id, card]));
  return cardIds.map((id) => {
    const card = byId.get(id);
    if (!card) throw new Error(`Неизвестная карта: ${id}`);
    return card;
  });
}
