/** Pure production prompt builder: no provider, network, credentials or server. */
export function buildManaraPrompts(rawInput: unknown) {
  const input = CreateManaraReadingBody.parse(rawInput);
  if (new Set(input.cardIds).size !== input.cardIds.length) {
    throw new Error("В раскладе не должно быть повторяющихся карт.");
  }
  const selectedCards = findManaraCards(input.cardIds);
  const orderedCards = selectedCards.map((card, index) => {
    const knowledge = manaraKnowledge[card.id];
    return {
      position: index + 1,
      id: card.id,
      name: card.name,
      arcana: card.arcana === "major" ? "Старший аркан" : "Младший аркан",
      suit: card.suit === "major" ? "Старший аркан" : card.suit,
      keywords: card.keywords,
      coreNote: knowledge.baseMeaning,
      shadowNote: card.shadow,
      reflectionHints: knowledge.reflectionQuestions,
      sourceNotes: knowledge.sourceNotes,
      sourceReferences: knowledge.sources,
    };
  });
  const userPrompt = JSON.stringify({
    question: input.question,
    querentGender: input.querentGender,
    readingMode: input.mode,
    orderedCards,
    spreadContext: {
      cardCount: selectedCards.length,
      positionMeaning: "Только порядок выбора; специальные значения позиций не заданы.",
      adjacentPairs: selectedCards.slice(0, -1).map((card, index) => ({
        first: { id: card.id, name: card.name, position: index + 1 },
        second: {
          id: selectedCards[index + 1].id,
          name: selectedCards[index + 1].name,
          position: index + 2,
        },
      })),
    },
    sourceTitlesForMethodContext: manaraSources,
    sourceTitlesById: Object.fromEntries(
      Object.entries(manaraSourceRegistry).map(([id, source]) => [id, source.title]),
    ),
    requiredShape: {
      overview: "целостная гипотеза и центральная динамика всего сочетания в контексте вопроса; если карт несколько — назови карты, на которых основан синтез",
      cardAnalysis: selectedCards.map((card, index) => ({
        cardId: card.id,
        cardName: card.name,
        position: index + 1,
        interpretation: "вклад карты в общую историю и как её смысл уточняется другими выбранными картами; не отдельная словарная трактовка",
        connectionToQuestion: "как это связано с вопросом и что остаётся гипотезой",
      })),
      cardDynamics: selectedCards.length > 1
        ? "связное совместное чтение: назови конкретные пары/сочетания, объясни изменение смысла, усиления и противоречия, затем собери все карты в общую гипотезу; не повторяй список значений"
        : "объясни предел одиночной карты: сочетаний в этом раскладе нет",
      likelyAnswer: "сдержанный ответ на исходный запрос из совместного чтения всего расклада, а не вердикт по одной карте; отдели гипотезы от известных фактов",
      alternativeReadings: ["минимум одна обоснованная альтернативная версия целого сочетания с опорой на конкретные выбранные карты"],
      reflectionQuestions: ["2–3 практичных вопроса для проверки реальности и своих границ"],
    },
  });
  const systemPrompt = MANARA_SYSTEM_PROMPT;
  const promptBytes = Buffer.byteLength(systemPrompt + userPrompt, "utf8");
  if (promptBytes > MANARA_PROMPT_MAX_BYTES) {
    throw new Error(`Контекст расклада превышает безопасный размер (${promptBytes}/${MANARA_PROMPT_MAX_BYTES} байт); источники не были обрезаны.`);
  }
  return { systemPrompt, userPrompt, selectedCards, promptBytes };
}
